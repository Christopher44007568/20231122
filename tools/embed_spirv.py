#!/usr/bin/env python3
"""Compile GLSL with glslang/glslc and emit a C++17 SPIR-V header."""

import pathlib
import subprocess
import sys


def find_compiler() -> str:
    for name in ("glslc", "glslangValidator", "glslang"):
        result = subprocess.run(
            ["sh", "-c", f"command -v {name}"],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    raise SystemExit("glslc, glslangValidator or glslang is required")


def emit_array(name: str, words: list[int]) -> str:
    lines = [f"static const uint32_t {name}[] = {{"]
    for offset in range(0, len(words), 8):
        chunk = ", ".join(f"0x{word:08x}u" for word in words[offset:offset + 8])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    root = pathlib.Path(__file__).resolve().parents[1]
    compiler = find_compiler()
    generated = []
    for shader in ("scene.vert", "scene.frag"):
        source = root / "shaders" / shader
        output = root / "build-shaders" / (shader + ".spv")
        output.parent.mkdir(parents=True, exist_ok=True)
        command = [compiler, str(source), "-o", str(output)]
        if pathlib.Path(compiler).name in ("glslang", "glslangValidator"):
            command.insert(1, "-V")
        subprocess.run(command, check=True)
        data = output.read_bytes()
        if len(data) % 4:
            raise SystemExit(f"invalid SPIR-V byte count for {shader}")
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        generated.append(emit_array(shader.replace(".", "_") + "_spv", words))

    header = root / "src" / "shaders_spv.h"
    header.write_text(
        "#pragma once\n\n#include <cstdint>\n\n"
        "// Generated by tools/embed_spirv.py; checked in for compiler-free builds.\n"
        + "\n\n".join(generated)
        + "\n",
        encoding="utf-8",
    )
    print(header)


if __name__ == "__main__":
    sys.exit(main())
